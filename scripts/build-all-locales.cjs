// Parse the existing fullLocalizedOverrides object
const match = existingContent.match(/export const fullLocalizedOverrides: Record<Exclude<Language, 'ar' \| 'en'>, Record<string, string>> = (\{[\s\S]*?\n\});/);
if (!match) {
  console.error("Could not match fullLocalizedOverrides in src/localesData.ts");
  process.exit(1);
}

const existingLocales = JSON.parse(match[1]);

// 1. Assign our pristine 100% complete Spanish dictionary
