// Export dictionary proxy that guarantees every key exists for every language
export const dictionary: Record<Language, typeof arDict> = new Proxy(baseDictionary, {
  get(target, prop: string) {
    const langKey = (prop in target ? prop : 'en') as Language;
    const langDict = target[langKey] || target.en;
    return new Proxy(langDict, {
      get(subTarget, key: string) {
        if (key in subTarget && (subTarget as Record<string, string>)[key]) {
          return (subTarget as Record<string, string>)[key];
        }
        // Fallback to English, or Arabic for RTL
        const fallback = (langKey === 'ar' || langKey === 'fa' || langKey === 'ur') ? target.ar : target.en;
        return (fallback as Record<string, string>)[key] || (target.en as Record<string, string>)[key] || '';
      }
    });
  }
});
