function formatSingleWord(raw: string): string {
  return (raw || '')
    .trim()
    .split(/\s+/)[0]
    .replace(/[،,.:;!?"'()[\]{}<>\\/]/g, '')
    .trim();
}

export function translateBotClueWord(word: string, targetLang: 'ar' | 'en'): string {
  const clean = formatSingleWord(word);
  if (!clean) return targetLang === 'ar' ? 'معروف' : 'popular';

  const hasArabic = /[\u0600-\u06FF]/.test(clean);
  if (targetLang === 'ar') {
    if (hasArabic) return clean;
    const mapped = CLUE_EN_TO_AR[clean.toLowerCase()];
    return mapped || 'مميز';
  }

  if (!hasArabic) return clean;
  const direct = CLUE_AR_TO_EN[clean];
  if (direct) return direct;
  const normalized = clean
    .replace(/[أإآ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي');
  return CLUE_AR_TO_EN[normalized] || 'special';
}
